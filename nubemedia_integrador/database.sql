-- NubeMedia: catálogo multimedia del producto integrador.
-- Ejecutar una sola vez en Neon > SQL Editor, base de datos neondb.
-- Esta tabla es independiente de productos y usuarios de la actividad 3.3.

CREATE TABLE IF NOT EXISTS public.media_resources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(140) NOT NULL,
    description VARCHAR(500) NOT NULL,
    category VARCHAR(30) NOT NULL CHECK (category IN ('Video', 'Música', 'Documento')),
    provider VARCHAR(50) NOT NULL,
    external_url TEXT NOT NULL UNIQUE,
    is_featured BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT media_resources_valid_url CHECK (external_url ~ '^https?://')
);

CREATE INDEX IF NOT EXISTS idx_media_resources_category
    ON public.media_resources (category)
    WHERE is_active = TRUE;

